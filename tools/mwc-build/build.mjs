/*=============================================================================
 * tools/mwc-build/build.mjs - build and inline the Material Web bundle
 *
 * @material/web 2.5.0 publishes GitHub-flavoured JS that imports CSS with
 * `with { type: 'css' }`. esbuild does not understand that import syntax, so
 * this script rewrites those imports to the generated `.cssresult.js` modules
 * before bundling. It also disables the list item's `::checkmark` (that glyph
 * needs Material Symbols, which the WebUI intentionally does not ship).
 *
 * The result is a single IIFE in module/webroot/index.html, so the manager
 * still serves one file and the UI stays offline.
 *===========================================================================*/
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const materialWeb = path.join(here, 'node_modules/@material/web');

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (entry.name.endsWith('.js')) out.push(p);
  }
  return out;
}

function patchMaterialWeb() {
  let changed = 0;
  for (const file of walk(path.join(materialWeb, 'labs/gb'))) {
    const before = fs.readFileSync(file, 'utf8');
    let text = before.replace(
      /from\s+(['"])([^'"]+\.css)\1\s+with\s*\{\s*type:\s*['"]css['"]\s*\};/g,
      (_, quote, p) => `from ${quote}${p.replace(/\.css$/, '.cssresult.js')}${quote};`,
    );
    if (file.endsWith('list.cssresult.js')) {
      // Material Symbols is not shipped; selection uses our own selbox.
      text = text.replace(/content:"check"/g, 'content:none');
    }
    if (text !== before) {
      fs.writeFileSync(file, text);
      changed++;
    }
  }
  console.log(`patched ${changed} Material Web source file(s)`);
}

patchMaterialWeb();

const bundlePath = path.join(here, 'index.bundle.js');
await build({
  entryPoints: [path.join(here, 'entry.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'chrome111',
  legalComments: 'none',
  outfile: bundlePath,
});

const bundle = fs.readFileSync(bundlePath, 'utf8').replace(/<\/script/gi, '<\\/script');
const header = '/* @material/web 2.5.0 (Apache-2.0) - generated by tools/mwc-build; see THIRD_PARTY_NOTICES.md */\n';
const indexPath = path.join(repo, 'module/webroot/index.html');
let html = fs.readFileSync(indexPath, 'utf8');
const marker = /<script id="mwc-bundle">[\s\S]*?<\/script>/;
if (!marker.test(html)) throw new Error('mwc-bundle marker not found in index.html');

// A replacer function is required: the minified bundle contains `$` sequences
// that String.replace would otherwise treat as capture-group references.
html = html.replace(marker, () => `<script id="mwc-bundle">${header}${bundle}\n</script>`);
fs.writeFileSync(indexPath, html);
console.log(`inlined ${bundle.length} chars into ${path.relative(repo, indexPath)}`);
