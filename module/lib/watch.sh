#!/system/bin/sh
#=============================================================================
# lib/watch.sh - 监听重启的退避计算
#
# 说明：这里只放**纯函数**（不读设备状态、不调外部命令），所以可以被
#       tests/watch-backoff.sh 直接 source 后逐档断言 —— 守护进程跑的
#       就是这一份，不存在"测的是一份、线上是另一份"。
#=============================================================================

# 监听进程活过多少秒就算"正常一轮"、把失败计数清零
WATCH_ALIVE=10

# 用法：next_backoff <连续失败次数>
# 返回：打印下一次重启前要等的秒数（3 → 6 → 12 → 24 → 48 → 60 封顶）
# 说明：第 1 次不吵、也不久等（多半是偶发的目录未就绪）；连续失败才指数退避，
#       上限 60 秒 —— 再长就等于监听名存实亡了，不如让日志停在一条 warn 上。
next_backoff() {
    local fails="${1:-1}"
    local sec

    if [ "$fails" -le 1 ]; then
        printf '3\n'
        return 0
    fi

    sec=$((3 << (fails - 1)))
    [ "$sec" -gt 60 ] && sec=60
    printf '%s\n' "$sec"
}
